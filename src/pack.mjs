import { createHash } from "node:crypto";
import { safeMetadataLabel } from "./privacy.mjs";

export const BLACKBOX_PACK_SCHEMA = "eversko.dsh-blackbox.pack.v1";

function sha256(value) {
  return createHash("sha256").update(String(value)).digest("hex");
}

function safeString(value) {
  return typeof value === "string" && value.length > 0 ? value : null;
}

export function createBlackBoxPack({
  header = {},
  report,
  artifact = null,
  runtimeVersion = null,
  generatedAt = Date.now(),
  sourceKind = "artifact",
}) {
  if (report?.schema !== "eversko.dsh-blackbox.report.v1") {
    throw new TypeError("report is not an Eversko DSH Black Box report");
  }
  if (!Number.isSafeInteger(generatedAt) || generatedAt < 0) {
    throw new TypeError("generatedAt must be a non-negative integer");
  }
  const sessionId = safeString(header.id);
  const cwd = safeString(header.cwd);
  return Object.freeze({
    schema: BLACKBOX_PACK_SCHEMA,
    generatedAt,
    privacy: Object.freeze({
      mode: "metadata-only",
      contentIncluded: false,
      pathsIncluded: false,
      rawSessionIdentifiersIncluded: false,
    }),
    source: Object.freeze({
      kind: sourceKind,
      runtimeVersion: safeMetadataLabel(runtimeVersion, "private-runtime"),
      sessionFormatVersion: Number.isSafeInteger(header.version)
        ? header.version
        : null,
      sessionIdHash: sessionId === null ? null : sha256(sessionId),
      workspaceHash: cwd === null ? null : sha256(cwd),
      agentPreset: safeMetadataLabel(header.agentPreset, "private-preset"),
      artifactEncoding: safeString(artifact?.encoding),
      artifactSha256: safeString(artifact?.sha256),
      artifactBytes: Number.isSafeInteger(artifact?.bytes) ? artifact.bytes : null,
    }),
    report,
  });
}

function markdownCell(value) {
  return String(value ?? "—")
    .replace(/[\r\n]+/gu, " ")
    .replace(/\|/gu, "\\|")
    .slice(0, 240);
}

export function renderBlackBoxMarkdown(pack) {
  if (pack?.schema !== BLACKBOX_PACK_SCHEMA) {
    throw new TypeError("pack is not an Eversko DSH Black Box pack");
  }
  const { report, source } = pack;
  const lines = [
    "# DSH Black Box report",
    "",
    `**Status:** ${report.status.toUpperCase()}  `,
    `**Runtime:** ${source.runtimeVersion ?? "not recorded"}  `,
    `**Agent preset:** ${source.agentPreset ?? "not recorded"}  `,
    `**Privacy:** metadata only; prompts, tool arguments, tool results, identifiers, and paths excluded`,
    "",
    "| Events | Turns | Steps | Tool calls | Approvals | Output characters | Duration |",
    "|---:|---:|---:|---:|---:|---:|---:|",
    `| ${report.summary.eventCount} | ${report.summary.turnCount} | ${report.summary.stepCount} | ${report.summary.toolCallCount} | ${report.summary.approvalCount} | ${report.summary.outputChars} | ${report.summary.durationMs} ms |`,
    "",
    "## Findings",
    "",
  ];
  if (report.anomalies.length === 0) {
    lines.push("No Black Box anomaly was detected.");
  } else {
    lines.push("| Severity | Finding | Event | Facts |", "|---|---|---:|---|");
    for (const anomaly of report.anomalies) {
      lines.push(
        `| ${markdownCell(anomaly.severity)} | ${markdownCell(anomaly.code)} | ${markdownCell(anomaly.eventSeq)} | ${markdownCell(JSON.stringify(anomaly.facts))} |`,
      );
    }
  }
  lines.push(
    "",
    "---",
    "Generated by DSH Black Box by Eversko. This report reconstructs recorded metadata; it does not rerun model or tool side effects.",
    "",
  );
  return lines.join("\n");
}
